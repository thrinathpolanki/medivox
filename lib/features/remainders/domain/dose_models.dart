import '../../../database/app_database.dart';
import '../../medicine/domain/medicine_models.dart';

enum DoseStatus {
  pending('Pending'),
  taken('Taken'),
  snoozed('Snoozed'),
  skipped('Skipped'),
  missed('Missed');

  const DoseStatus(this.label);
  final String label;
  static DoseStatus byName(String n) =>
      DoseStatus.values.firstWhere((s) => s.name == n, orElse: () => DoseStatus.pending);
}

/// One scheduled dose occurrence joined with its medicine and schedule.
class DoseItem {
  const DoseItem(this.dose, this.medicine, this.schedule);
  final DoseRecord dose;
  final Medicine medicine;
  final MedicationSchedule? schedule; // null if the schedule was deleted later

  DoseStatus get status => DoseStatus.byName(dose.status);
  DateTime get scheduledAt => dose.scheduledAt;

  String get title {
    final s = (medicine.strength ?? '').trim();
    return s.isEmpty ? medicine.medicineName : '${medicine.medicineName} $s';
  }

  /// Always the user-entered dosage; never generated by the app.
  String get dosageText {
    final fromSchedule = schedule?.dosage.trim() ?? '';
    return fromSchedule.isNotEmpty ? fromSchedule : (medicine.dosage ?? '').trim();
  }

  FoodInstruction get food =>
      schedule == null ? FoodInstruction.asPrescribed : FoodInstruction.byName(schedule!.foodInstruction);
  SchedulePeriod get period =>
      schedule == null ? SchedulePeriod.custom : SchedulePeriod.byName(schedule!.period);
}

class ReminderText {
  static const title = 'Time to take your medicine';
  static String body(DoseItem d) {
    final parts = <String>[d.title];
    if (d.dosageText.isNotEmpty) parts.add(d.dosageText);
    parts.add(d.food.label);
    return parts.join(' · ');
  }
}
