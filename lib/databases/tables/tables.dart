import 'package:drift/drift.dart';

@DataClassName('UserProfile')
class UserProfiles extends Table {
  TextColumn get userId => text()();
  TextColumn get displayName => text().nullable()();
  TextColumn get storageMode => text()();
  TextColumn get preferredLanguage => text().nullable()();
  DateTimeColumn get createdAt => dateTime()();
  @override
  Set<Column> get primaryKey => {userId};
}

@DataClassName('Medicine')
@TableIndex(name: 'idx_medicines_user', columns: {#userId})
@TableIndex(name: 'idx_medicines_name', columns: {#medicineName})
class Medicines extends Table {
  TextColumn get medicineId => text()();
  TextColumn get userId =>
      text().customConstraint('NOT NULL REFERENCES user_profiles (user_id) ON DELETE CASCADE')();
  TextColumn get medicineName => text().withLength(min: 1, max: 200)();
  TextColumn get genericName => text().nullable()();
  TextColumn get strength => text().nullable()();
  TextColumn get composition => text().nullable()();
  TextColumn get manufacturer => text().nullable()();
  TextColumn get medicineType => text().nullable()();
  // Exactly what the user/prescription says. Never generated by the app.
  TextColumn get dosage => text().nullable()();
  TextColumn get prescriptionReference => text().nullable()();
  TextColumn get notes => text().nullable()();
  DateTimeColumn get startDate => dateTime().nullable()();
  DateTimeColumn get endDate => dateTime().nullable()();
  BoolColumn get reminderEnabled =>
      boolean().withDefault(const Constant(true))();
  DateTimeColumn get createdAt => dateTime()();
  DateTimeColumn get updatedAt => dateTime()();
  IntColumn get revision => integer().withDefault(const Constant(1))();
  TextColumn get syncStatus =>
      text().withDefault(const Constant('local_only'))();
  @override
  Set<Column> get primaryKey => {medicineId};
}

@DataClassName('MedicineImage')
@TableIndex(name: 'idx_images_medicine', columns: {#medicineId})
class MedicineImages extends Table {
  TextColumn get imageId => text()();
  TextColumn get medicineId =>
      text().customConstraint('NOT NULL REFERENCES medicines (medicine_id) ON DELETE CASCADE')();
  TextColumn get imageType => text()(); // strip_front | strip_back | tablet
  IntColumn get imageSequence => integer()();
  TextColumn get localPath => text()();
  TextColumn get cloudPath => text().nullable()();
  TextColumn get checksum => text().nullable()();
  @override
  Set<Column> get primaryKey => {imageId};
  @override
  List<Set<Column>> get uniqueKeys => [
        {medicineId, imageType, imageSequence}
      ];
}

@DataClassName('MedicationSchedule')
@TableIndex(name: 'idx_schedules_medicine', columns: {#medicineId})
class MedicationSchedules extends Table {
  TextColumn get scheduleId => text()();
  TextColumn get medicineId =>
      text().customConstraint('NOT NULL REFERENCES medicines (medicine_id) ON DELETE CASCADE')();
  TextColumn get period => text()(); // morning|afternoon|night|custom
  TextColumn get time => text()(); // HH:mm (24h, local wall-clock)
  TextColumn get dosage => text()();
  TextColumn get foodInstruction => text()();
  TextColumn get repeatRule => text()(); // 7 chars Mon..Sun, '1' = repeat
  TextColumn get timezone => text().nullable()();
  DateTimeColumn get startDate => dateTime()();
  DateTimeColumn get endDate => dateTime().nullable()();
  BoolColumn get enabled => boolean().withDefault(const Constant(true))();
  @override
  Set<Column> get primaryKey => {scheduleId};
}

/// Created now so the schema is stable; used from Milestone 3 (reminders).
@DataClassName('DoseRecord')
@TableIndex(name: 'idx_dose_medicine', columns: {#medicineId})
@TableIndex(name: 'idx_dose_scheduled', columns: {#scheduledAt})
class DoseHistoryEntries extends Table {
  @override
  String get tableName => 'dose_history';
  TextColumn get doseId => text()();
  TextColumn get medicineId =>
      text().customConstraint('NOT NULL REFERENCES medicines (medicine_id) ON DELETE CASCADE')();
  TextColumn get scheduleId => text().nullable().customConstraint(
      'REFERENCES medication_schedules (schedule_id) ON DELETE SET NULL')();
  DateTimeColumn get scheduledAt => dateTime()();
  DateTimeColumn get actionAt => dateTime().nullable()();
  // pending | taken | snoozed | skipped | missed
  TextColumn get status => text().withDefault(const Constant('pending'))();
  TextColumn get notes => text().nullable()();
  @override
  Set<Column> get primaryKey => {doseId};
}

